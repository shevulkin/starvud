// Попередній перегляд банера. Рядок збирається тут точно так само, як у
// layouts/main.php, — щоб було видно, що відсоток лише склеюється з текстом.
// Порожній відсоток там дає «0» (Settings::get підставляє значення за
// замовчуванням), тож і тут показуємо −0%, а не порожнечу.
(function () {
  var txt = document.getElementById('saleText'), pct = document.getElementById('salePercent'),
      act = document.getElementById('saleActive'), out = document.getElementById('salePreview');
  if (!txt || !out) return;
  function draw() {
    out.textContent = act.checked
      ? (txt.value + ' · −' + (pct.value !== '' ? pct.value : '0') + '%')
      : 'нічого — банер вимкнено';
  }
  [txt, pct, act].forEach(function (el) { el.addEventListener('input', draw); el.addEventListener('change', draw); });
  draw();
})();
</script>

