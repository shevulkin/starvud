<?php
declare(strict_types=1);

/**
 * Диплом випускника — з боку студента.
 *
 * Публічна перевірка справжності за номером живе окремо (/diploma/check): вона
 * відповідає на питання роботодавця «цей папірець справжній?». Тут — питання
 * самого випускника: «які дипломи мої».
 *
 * Відповісти на нього можна лише за звʼязком із акаунтом. Імені на бланку для
 * цього не досить: тезки існують, прізвища міняються, а приписати людині чужий
 * диплом гірше, ніж не показати їй власний. Тому diplomas.user_id — і тому він
 * необовʼязковий: диплом видають і тим, хто акаунта не заводив.
 */
class Diplomas
{
    /** Дипломи цієї людини — лише дійсні: відкликаний диплом не її досягнення */
    public static function forUser(int $userId): array
    {
        return DB::all(
            'SELECT * FROM diplomas WHERE user_id = ? AND active = 1 ORDER BY issued_at DESC, id DESC',
            [$userId]);
    }

    /**
     * Назва курсу для бланка.
     *
     * Береться текстове поле, а не назва товару, і саме в такому порядку:
     * назву курсу в каталозі перейменують («…на технологіях США 2027»), а на
     * виданому дипломі має лишитись те, що там і надруковано. Товар підставляє
     * назву лише тоді, коли текст не заповнили.
     */
    public static function courseLabel(array $d): string
    {
        $text = trim((string)($d['course'] ?? ''));
        if ($text !== '') return $text;
        if (!empty($d['product_id'])) {
            return (string)(DB::val('SELECT name FROM products WHERE id = ?', [(int)$d['product_id']]) ?? '');
        }
        return '';
    }
}
